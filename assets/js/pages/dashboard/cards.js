// ------------------------------------------------------------------
// dashboard/cards.js - The dashboard's four card sections: API
// reference, reviews, knowledge and tools (docs/plan/50-DASHBOARD.md).
// Pure builders, data in and HTML out, no DOM and no fetching, so they
// load in a Node vm for testing (tests/unit/dashboard/cards.test.js).
//
// The theme running through all four: a link is worth more when it
// carries the state of what it links to. A card that says "API
// reference" is a shortcut; one that says "256 endpoints, 60.5% of the
// routes accounted for, 22 gaps" is information, and the click is the
// same click.
// ------------------------------------------------------------------

(function () {
  "use strict";

  window.App = window.App || {};

  var esc = App.escape;
  function plural(n, one, many) { return esc(n) + " " + (n === 1 ? one : many); }

  var FAMILY = { launchpad: "LaunchPad", unity: "Unity" };
  var MATURITY = ["live", "partial", "planned", "exploratory"];

  App.dashboardCards = {};

  // --- API reference -----------------------------------------------

  // Coverage comes from supabase/reference-coverage.json, generated by
  // a session with both the reference and a LaunchPad checkout
  // (docs/plan/20-API-REFERENCE.md). It is a static asset, not a query.
  // A spec with no source to compare against says so rather than
  // showing a percentage that would read as verified.
  App.dashboardCards.coverageLine = function (spec, coverage) {
    var found = coverage && coverage.specs && coverage.specs[spec.title];
    if (!found) return "";
    if (!found.comparable) return "Not verifiable against source";
    return esc(found.accounted_pct) + "% of " +
      plural(found.routes, "route", "routes") + " accounted for";
  };

  // The gaps, named rather than summed. One number would have read as
  // "3 gaps to close" on a spec with 196 undocumented routes, because
  // the badge counts are small and the absent count is not - and the
  // biggest gap is the one a summary must not hide.
  App.dashboardCards.gapsLine = function (spec, coverage) {
    var found = coverage && coverage.specs && coverage.specs[spec.title];
    if (!found) return "";
    var parts = [];
    if (found.absent > 0) {
      parts.push(plural(found.absent, "route not documented", "routes not documented"));
    }
    if (found.phantom > 0) {
      parts.push(plural(found.phantom, "row with no route", "rows with no route"));
    }
    if (found.undeclared_mirrors > 0) {
      parts.push(plural(found.undeclared_mirrors, "undeclared mirror", "undeclared mirrors"));
    }
    if (found.gap_badges > 0) parts.push(plural(found.gap_badges, "gap flagged", "gaps flagged"));
    if (found.unverified_badges > 0) {
      parts.push(plural(found.unverified_badges, "row unverified", "rows unverified"));
    }
    return parts.join(" &middot; ");
  };

  App.dashboardCards.specCard = function (spec, opts) {
    opts = opts || {};
    var href = opts.href ? opts.href(spec) : "#";
    var coverage = App.dashboardCards.coverageLine(spec, opts.coverage);
    var gaps = App.dashboardCards.gapsLine(spec, opts.coverage);
    var size = [
      spec.endpoints ? plural(spec.endpoints, "endpoint", "endpoints") : "",
      spec.tags ? plural(spec.tags, "tag", "tags") : "",
      spec.topics ? plural(spec.topics, "topic", "topics") : "",
    ].filter(Boolean).join(" &middot; ");
    return '<a class="card ds-spec" href="' + esc(href) + '">' +
      '<span class="eyebrow">' + esc(FAMILY[spec.family] || spec.family) + "</span>" +
      "<h3>" + esc(spec.title) + "</h3>" +
      '<p class="ds-spec-meta">' + App.statusBadge(spec.status) +
      '<span class="ds-spec-version">' + esc(spec.version) + "</span></p>" +
      (size ? '<p class="card-meta">' + size + "</p>" : "") +
      (coverage ? '<p class="ds-spec-coverage">' + coverage + "</p>" : "") +
      (gaps ? '<p class="ds-spec-gaps">' + gaps + "</p>" : "") +
      "</a>";
  };

  App.dashboardCards.specs = function (specs, opts) {
    if (!specs || !specs.length) {
      return '<p class="notice">No API specs recorded yet. Specs are rows in the ' +
        "api_specs table.</p>";
    }
    return '<div class="card-grid ds-specs">' + specs.map(function (spec) {
      return App.dashboardCards.specCard(spec, opts);
    }).join("") + "</div>";
  };

  // --- Reviews -----------------------------------------------------

  // The single next action, in words. A count is a fact; "7 still to
  // confirm" is a thing to do, and the difference is the whole reason
  // this section exists rather than another counter.
  App.dashboardCards.waveAction = function (wave) {
    // A portal or code wave answers a different question from an
    // application wave, so it gets its own ladder rather than a
    // borrowed one with zeroes in it.
    if (wave.kind && wave.kind !== "application") {
      if (wave.walked < wave.areas) {
        var left = wave.areas - wave.walked;
        return plural(left, "area still to walk", "areas still to walk");
      }
      if (wave.awaiting_verification > 0) {
        return plural(wave.awaiting_verification,
          "answer waiting on your verification", "answers waiting on your verification");
      }
      if (wave.findings_open > 0) {
        return plural(wave.findings_open,
          "finding open with the developers", "findings open with the developers");
      }
      return "Nothing outstanding. The wave is ready to triage.";
    }
    if (wave.needs_action > 0) {
      return plural(wave.needs_action, "application needs action", "applications need action");
    }
    if (wave.unconfirmed > 0) {
      return plural(wave.unconfirmed, "classification still to confirm",
        "classifications still to confirm");
    }
    return "Every application is classified and confirmed";
  };

  var WAVE_KIND = {
    application: "Application review",
    portal: "Portal review",
    code: "Code review",
  };

  // What a wave is made of, in its own units.
  function waveSize(wave) {
    if (wave.kind && wave.kind !== "application") {
      return esc(wave.walked || 0) + " of " + plural(wave.areas || 0, "area", "areas") +
        " walked";
    }
    return plural(wave.applications || 0, "application", "applications");
  }

  App.dashboardCards.reviews = function (waves, opts) {
    opts = opts || {};
    if (!waves || !waves.length) {
      return '<p class="notice">No review wave is open. Start one in a Claude ' +
        "session with /app-review or /portal-review.</p>";
    }
    return '<div class="card-grid ds-waves">' + waves.map(function (wave) {
      var opened = wave.opened_at ? String(wave.opened_at).slice(0, 10) : "";
      return '<a class="card ds-wave" href="' +
        esc(opts.href ? opts.href(wave) : "#") + '">' +
        '<span class="eyebrow">' +
        esc(WAVE_KIND[wave.kind] || WAVE_KIND.application) + "</span>" +
        "<h3>" + esc(wave.name) + "</h3>" +
        '<p class="ds-wave-action">' + App.dashboardCards.waveAction(wave) + "</p>" +
        '<p class="card-meta">' + waveSize(wave) +
        (opened ? " &middot; opened " + esc(opened) : "") + "</p></a>";
    }).join("") + "</div>";
  };

  // --- Knowledge ---------------------------------------------------

  // Figures, then the gaps beside them. A gap should be something to
  // fill, not something to discover - the platform page's principle,
  // and this is where it gets seen.
  App.dashboardCards.knowledgeGaps = function (k) {
    var gaps = [];
    if (k.areas_without_capability > 0) {
      gaps.push(plural(k.areas_without_capability,
        "product area has no capability recorded",
        "product areas have no capability recorded"));
    }
    if (k.capabilities_without_source > 0) {
      gaps.push(plural(k.capabilities_without_source,
        "capability has no source document",
        "capabilities have no source document"));
    }
    return gaps;
  };

  App.dashboardCards.knowledge = function (k, opts) {
    opts = opts || {};
    if (!k) return "";
    var maturity = k.by_maturity || {};
    var chips = MATURITY.filter(function (key) { return maturity[key]; })
      .map(function (key) {
        return '<span class="badge ' + esc(key) + '">' + esc(maturity[key]) + " " +
          esc(key) + "</span>";
      }).join(" ");
    var figures = [
      k.terms ? plural(k.terms, "glossary term", "glossary terms") : "",
      k.stages ? plural(k.stages, "journey stage", "journey stages") : "",
      k.documents ? plural(k.documents, "source document", "source documents") : "",
    ].filter(Boolean).join(" &middot; ");
    var gaps = App.dashboardCards.knowledgeGaps(k);
    var href = esc(opts.href || "#");
    if (!chips && !figures && !gaps.length) {
      return '<p class="notice">Nothing recorded yet. Platform knowledge lands in ' +
        "product_capabilities; see docs/PLATFORM.md.</p>";
    }
    return '<div class="ds-knowledge">' +
      (chips ? '<p class="ds-chips">' + chips + "</p>" : "") +
      (figures ? '<p class="card-meta">' + figures + "</p>" : "") +
      (gaps.length
        ? '<ul class="ds-gaps">' + gaps.map(function (gap) {
            return '<li><a href="' + href + '">' + gap + "</a></li>";
          }).join("") + "</ul>"
        : '<p class="ds-gaps-none">No gaps recorded against the knowledge base.</p>') +
      "</div>";
  };

  // --- Tools -------------------------------------------------------

  // The nav carries these as icons with tooltips and explains none of
  // them. Cards are built from portal_links rows, so adding a tool
  // stays a database insert and the target never enters this repo.
  App.dashboardCards.tools = function (rows) {
    var usable = (rows || []).filter(function (row) {
      return row && row.label && App.tools && App.tools.href(row);
    });
    if (!usable.length) {
      return '<p class="notice">No tools linked yet. Each one is a row in the ' +
        "portal_links table.</p>";
    }
    return '<div class="card-grid ds-tools">' + usable.map(function (row) {
      return '<a class="card ds-tool" href="' + esc(App.tools.href(row)) +
        '" target="_blank" rel="noopener noreferrer">' +
        "<h3>" + esc(row.label) + "</h3>" +
        '<p class="card-meta">' + (row.description
          ? esc(row.description)
          : "No description recorded. Add one to this portal_links row.") +
        "</p><span class=\"ds-tool-out\">Opens in a new tab</span></a>";
    }).join("") + "</div>";
  };
})();
