#!/usr/bin/env node
// ------------------------------------------------------------------
// scripts/gen-knowledge.js - Generates supabase/knowledge-coverage.json,
// the repo's committed account of whether what the system was told is
// still anchored, sourced and reachable.
//
// Why this exists. The gates that came before it check STRUCTURE: that
// a vocabulary is documented, that a stored value renders somewhere,
// that the reference matches the code. None of them notices when
// CONTENT decays - a note that lost its anchor, a term with no source,
// a link nobody ever confirmed. Those are the failures that matter to
// the person supplying the content, because the promise they are
// relying on is that what they say does not get lost. Twenty orphan
// notes existed for weeks and nothing failed.
//
// Same trick as reference-coverage.json and schema-snapshot.json: the
// suite has no database access by design, so the measurement happens
// once in a session that does, into an artefact of COUNTS ONLY - never
// a title, a body or an id - and tests/checks/knowledge-drift.test.js
// reads that.
//
// Usage (needs a session with Supabase MCP access):
//   npm run knowledge                  print the SQL to run
//   <run it, save the single json value to a file>
//   node scripts/gen-knowledge.js --write < result.json
// ------------------------------------------------------------------
"use strict";
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "supabase", "knowledge-coverage.json");

// Each figure is a COUNT of rows failing one integrity rule, plus the
// total it is drawn from so a percentage is derivable without a second
// query. Nothing here identifies a row.
const SQL = `-- Generated by scripts/gen-knowledge.js. Returns one json value.
-- Counts only: no title, body, id or path may appear in the result.
select jsonb_build_object(
  'notes', jsonb_build_object(
    'total', (select count(*) from work_notes),
    'orphaned', (select count(*) from work_notes
                 where work_item_id is null and document_id is null)),
  'terms', jsonb_build_object(
    'total', (select count(*) from domain_terms),
    'no_definition', (select count(*) from domain_terms
                      where coalesce(btrim(definition), '') = ''),
    'no_source', (select count(*) from domain_terms
                  where coalesce(btrim(source), '') = '')),
  'stages', jsonb_build_object(
    'total', (select count(*) from journey_stages),
    'no_source', (select count(*) from journey_stages
                  where coalesce(btrim(source), '') = '')),
  'capabilities', jsonb_build_object(
    'total', (select count(*) from product_capabilities),
    'no_area', (select count(*) from product_capabilities where area_id is null)),
  'links', jsonb_build_object(
    'live', (select count(*) from knowledge_links where valid_to is null),
    'proposed', (select count(*) from knowledge_links
                 where valid_to is null and confidence = 'proposed')),
  'items', jsonb_build_object(
    'total', (select count(*) from work_items),
    'no_summary', (select count(*) from work_items
                   where level <> 'workstream' and coalesce(btrim(summary), '') = ''),
    'closed_without_resolution', (select count(*) from work_items
                                  where status in ('done', 'dropped')
                                    and coalesce(btrim(resolution), '') = '')),
  'ideas', jsonb_build_object(
    'total', (select count(*) from future_prototypes),
    'no_summary', (select count(*) from future_prototypes
                   where coalesce(btrim(summary), '') = ''),
    'no_value_note', (select count(*) from future_prototypes
                      where coalesce(btrim(value_note), '') = '')),
  'documents', jsonb_build_object(
    'total', (select count(*) from work_documents),
    'no_digest', (select count(*) from work_documents
                  where coalesce(btrim(summary), '') = '')),
  'findings', jsonb_build_object(
    'live', (select count(*) from review_findings where deleted_at is null),
    'promoted_without_item', (select count(*) from review_findings
                              where deleted_at is null and disposition = 'promoted'
                                and promoted_work_item_id is null)),
  'embeddings', jsonb_build_object(
    'stale', (select count(*) from work_items_unembedded))
) as payload;`;

// The rules, each stated once here with the reason it is a rule. The
// gate reads this list, so adding a figure to the SQL without adding
// it here is caught rather than silently uncounted.
const RULES = [
  { key: "notes.orphaned", of: "notes.total",
    why: "A note anchored to neither an item nor a document is content the owner supplied that nothing links to. It is not lost, but it is unreachable from anywhere a reader would look." },
  { key: "terms.no_definition", of: "terms.total",
    why: "A glossary entry that names a term without defining it teaches nobody anything." },
  { key: "terms.no_source", of: "terms.total",
    why: "A definition with no source cannot be told from one somebody guessed. Provenance is the whole point of the glossary." },
  { key: "stages.no_source", of: "stages.total",
    why: "Same rule as the glossary: a stage with no source is an assertion." },
  { key: "capabilities.no_area", of: "capabilities.total",
    why: "A capability filed under no area does not appear on the platform page's sections, so it is stored and effectively invisible." },
  { key: "links.proposed", of: "links.live",
    why: "A proposed link is an assistant's suggestion the owner has not confirmed. Not a defect - it is the honest state - but it is the queue, and a queue nobody watches is a queue that grows." },
  { key: "items.no_summary", of: "items.total",
    why: "A title alone is unreadable six months later, which is exactly when it gets read." },
  { key: "items.closed_without_resolution", of: "items.total",
    why: "Nothing is ever deleted means a closed item carries why it closed. A done or dropped row with no resolution has lost the decision." },
  { key: "ideas.no_summary", of: "ideas.total",
    why: "A prototype idea that is only a name cannot be prioritised or dropped on its merits." },
  { key: "ideas.no_value_note", of: "ideas.total",
    why: "What an idea would PROVE is the field that decides whether to build it. Without it the board is a wish list." },
  { key: "documents.no_digest", of: "documents.total",
    why: "docs/WORKFLOW.md says raw material AND a digest go to work_documents; the digest is the summary column. A document with none is a paste nobody distilled - the material is there and the meaning is not." },
  { key: "findings.promoted_without_item", of: "findings.live",
    why: "A finding marked promoted with no work item is a claim with nothing behind it. The schema constrains this; the count proves the constraint holds." },
  { key: "embeddings.stale", of: "items.total",
    why: "An item whose vector was computed from text that has since changed still answers searches - with the wrong meaning, silently. work_items_unembedded is the one place that knows; this is what makes it visible without asking. Clear it with select * from roadmap_embed_refresh()." },
];

function dig(payload, dotted) {
  return dotted.split(".").reduce((o, k) => (o == null ? o : o[k]), payload);
}

function build(payload) {
  const figures = {};
  for (const rule of RULES) {
    const n = dig(payload, rule.key);
    const of = dig(payload, rule.of);
    if (typeof n !== "number" || typeof of !== "number") {
      throw new Error("missing figure for " + rule.key + " - the SQL and RULES disagree");
    }
    figures[rule.key] = { n: n, of: of, pct: of ? Math.round((n / of) * 1000) / 10 : 0 };
  }
  return {
    generated_note: "GENERATED by scripts/gen-knowledge.js. Counts only - no title, " +
      "body, id or path. Do not edit by hand.",
    generated_on: new Date().toISOString().slice(0, 10),
    totals: {
      notes: payload.notes.total, terms: payload.terms.total,
      stages: payload.stages.total, capabilities: payload.capabilities.total,
      links: payload.links.live, items: payload.items.total,
      ideas: payload.ideas.total, documents: payload.documents.total,
      findings: payload.findings.live,
    },
    figures: figures,
  };
}

if (require.main === module) {
  if (!process.argv.includes("--write")) {
    console.log(SQL);
    process.exit(0);
  }
  const payload = JSON.parse(fs.readFileSync(0, "utf8"));
  const artefact = build(payload.payload || payload);
  fs.writeFileSync(OUT, JSON.stringify(artefact, null, 2) + "\n");
  console.log("wrote " + path.relative(ROOT, OUT));
  for (const [key, f] of Object.entries(artefact.figures)) {
    console.log("  " + key.padEnd(36) + String(f.n).padStart(4) + " of " +
      String(f.of).padStart(4) + "  (" + f.pct + "%)");
  }
}

module.exports = { SQL, RULES, build };
