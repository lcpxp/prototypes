#!/usr/bin/env node
// ------------------------------------------------------------------
// scripts/gen-coverage.js - Generates supabase/reference-coverage.json,
// the repo's committed account of how far the API reference matches
// the code it documents.
//
// Two inputs meet here: the reference (from the live database, via the
// SQL below) and the route inventory (from a scratch checkout, via
// scripts/extract-routes.js). Neither of them may enter this public
// repo, so the artefact carries COUNTS and one DIGEST per spec -
// never a path, a host or a payload. That is what lets
// tests/checks/reference-drift.test.js run with no network and no
// credentials, the same trick supabase/schema-snapshot.json uses.
//
// Usage (needs a session with Supabase MCP access):
//   npm run coverage                     print the SQL to run
//   <run it, save the single json value to a file>
//   node scripts/gen-coverage.js --write --source <presentation-dir> < result.json
// ------------------------------------------------------------------
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const { extractDir, routeKey } = require("./extract-routes.js");
const { extractDir: extractCalls } = require("./extract-calls.js");

const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "supabase", "reference-coverage.json");

const SQL = `-- Generated by scripts/gen-coverage.js. Returns one json value.
-- Endpoint keys are normalised here the same way scripts/extract-routes.js
-- normalises code routes: placeholders positional, comparison case-folded.
-- The keys are reconciled in memory and never written to the repo.
select jsonb_pretty(jsonb_build_object(
  'specs', (
    select jsonb_agg(jsonb_build_object(
      'title', s.title,
      'version', s.version,
      'status', s.status,
      'family', s.family,
      'endpoints', (select count(*) from api_endpoints e where e.spec_id = s.id),
      'distinct_keys', (
        select count(distinct upper(e.method) || ' ' ||
          lower(regexp_replace(e.path, '\\{[^}]+\\}', '{}', 'g')))
        from api_endpoints e where e.spec_id = s.id
      ),
      'tags', (select count(*) from api_tags t where t.spec_id = s.id),
      'topics', (select count(*) from api_topics p where p.spec_id = s.id),
      'keys', (
        select coalesce(jsonb_agg(distinct
          upper(e.method) || ' ' ||
          lower(regexp_replace(e.path, '\\{[^}]+\\}', '{}', 'g'))), '[]'::jsonb)
        from api_endpoints e where e.spec_id = s.id
      ),
      'badges', (
        select coalesce(jsonb_object_agg(label, n), '{}'::jsonb) from (
          select b->>'label' as label, count(*) as n
          from api_endpoints e, lateral jsonb_array_elements(e.badges) b
          where e.spec_id = s.id and b->>'label' is not null
          group by 1
        ) c
      ),
      -- Rows that state the scope collapse on their face. A collapse
      -- only counts as declared when the row it points at says so, so
      -- this is the evidence for that, matched in memory and never
      -- written to the repo.
      'scope_keys', (
        select coalesce(jsonb_agg(distinct
          upper(e.method) || ' ' ||
          lower(regexp_replace(e.path, '\\{[^}]+\\}', '{}', 'g'))), '[]'::jsonb)
        from api_endpoints e
        where e.spec_id = s.id
          and exists (
            select 1 from jsonb_array_elements(e.badges) b
            where b->>'label' like '%scope%'
          )
      )
    ) order by s.title)
    from api_specs s
  )
));`;

// Scope collapses: one documented row standing for the same operation
// under several prefixes. `declared` means the reference says so, in a
// badge and a note on the row; an undeclared collapse is reported
// separately because a reader who cannot see the convention has to
// guess. Adding a rule here is how a new collapse gets counted.
const COLLAPSES = [
  // Order matters: a route stands on the FIRST documented twin, so the
  // more specific rule is listed first. Product addons exist under
  // both scope prefixes and unscoped; the sales-team form belongs to
  // the partner row, and letting it reach the unscoped row instead
  // would mark a row nothing calls as live.
  { declared: true, from: /^\/api\/v2\/sales-teams\/\{\}\//, to: "/api/v2/partners/{}/" },
  { declared: true, from: /^\/api\/v2\/partners\/\{\}\//, to: "/api/v2/" },
  { declared: true, from: /^\/api\/v2\/sales-teams\/\{\}\//, to: "/api/v2/" },
  // The v1 merchant surface serves the same twenty operations under
  // three prefixes - unscoped, admin and partner - with identical
  // shapes and different visibility. Documenting sixty rows for twenty
  // operations would bury the difference that matters. The third rule
  // is for the operations only two of the arms serve: the canonical
  // path does not exist, so the partner row is the one that stands.
  { declared: true, from: /^\/api\/v1\/partner\/merchant/, to: "/api/v1/merchants" },
  { declared: true, from: /^\/api\/v1\/admin\/merchant/, to: "/api/v1/merchants" },
  { declared: true, from: /^\/api\/v1\/admin\/merchant/, to: "/api/v1/partner/merchant" },
  // The user surface is the same six operations under two prefixes,
  // identical on all six - checked signature by signature. The
  // merchant LIST is not: the admin and partner forms return different
  // read models and take different query parameters, so it keeps two
  // rows and no rule absorbs it.
  { declared: true, from: /^\/api\/v1\/partner\/users/, to: "/api/v1/admin/users" },
  // A v2 operation that exists under the two scope prefixes but has no
  // unscoped form: product addons. The partner row is the one that
  // stands, as with the two-arm merchant operations.
  { declared: true, from: /^\/api\/v2\/sales-teams\/\{\}\//, to: "/api/v2/partners/{}/" },
];

function collapsedKeys(key, declaredOnly) {
  const [method, p] = [key.slice(0, key.indexOf(" ")), key.slice(key.indexOf(" ") + 1)];
  const out = [];
  for (const rule of COLLAPSES) {
    if (declaredOnly && !rule.declared) continue;
    if (!rule.from.test(p)) continue;
    out.push({ key: method + " " + p.replace(rule.from, rule.to), declared: rule.declared });
  }
  return out;
}

// `declared` is a claim about the REFERENCE, not about the code: it
// means a reader can see the convention, in a badge and a note on the
// row the collapse points at. Marking a rule declared here does not
// make it so - only the badge does. So a route counts as a declared
// variant only when the row it collapses onto actually carries the
// badge, and a rule flipped to declared without the rows being badged
// makes coverage fall rather than rise. That is the intended
// direction: it is the difference between the convention being stated
// and someone having decided it is obvious.
function declaredOn(twin, docs, scoped) {
  return twin.declared && docs.has(twin.key) && (!scoped || scoped.has(twin.key));
}

// A call inventory turns "documented?" into "documented, and does
// anything call it?". Those are different questions and the second one
// decides what a reader should be shown as current, so it is DERIVED
// here on every run rather than recorded on a row. A hand-set "not
// called" flag is wrong the day someone wires up a controller, and
// nothing would fail.
//
// A route the portal calls can match a documented row through a
// collapse, so callability is tested against the same twin rules the
// documentation match uses.
function callState(key, calls) {
  if (calls.has(key)) return true;
  // A call site that passes a segment the API declares as a literal -
  // `service-fees/${type}` against /service-fees/ecom and five more -
  // reaches every one of them. Same method, same segment count, a {}
  // in the call standing where the code has a literal.
  const [method, p] = [key.slice(0, key.indexOf(" ")), key.slice(key.indexOf(" ") + 1)];
  const want = p.split("/");
  for (const call of calls) {
    if (!call.startsWith(method + " ")) continue;
    const got = call.slice(method.length + 1).split("/");
    if (got.length !== want.length) continue;
    if (want.every((seg, i) => seg === got[i] || (got[i] === "{}" && seg !== "{}"))) return true;
  }
  return false;
}

// The whole reconciliation, as a pure function so the gate's arithmetic
// can be benchmarked without a database or a checkout.
function reconcile(routeKeys, docKeys, callKeys, scopeKeys) {
  const routes = new Set(routeKeys);
  const docs = new Set(docKeys);
  const calls = new Set(callKeys || []);
  // Rows that carry a scope-collapse badge. Undefined means the
  // payload predates the check, in which case a declared rule is
  // taken at its word.
  const scoped = scopeKeys ? new Set(scopeKeys) : null;
  const result = {
    routes: routes.size, documented: docs.size,
    matched: 0, phantom: 0, scope_variants: 0, undeclared_mirrors: 0, absent: 0,
  };
  for (const key of docs) if (routes.has(key)) result.matched++;
  result.phantom = docs.size - result.matched;
  for (const key of routes) {
    if (docs.has(key)) continue;
    const twins = collapsedKeys(key, false);
    const declared = twins.some((t) => declaredOn(t, docs, scoped));
    const undeclared = twins.some((t) => docs.has(t.key)) && !declared;
    if (declared) result.scope_variants++;
    else if (undeclared) result.undeclared_mirrors++;
    else result.absent++;
  }
  result.accounted = result.matched + result.scope_variants;
  result.accounted_pct = routes.size
    ? Math.round((result.accounted / routes.size) * 1000) / 10 : 0;
  if (!calls.size) return result;

  // called      routes a front-end call site reaches
  // uncalled    routes nothing calls - whole features, not strays
  // gap         called AND undocumented: the work that actually
  //             matters, and the only figure worth driving to zero
  // stale_docs  documented ROWS with no live route under them
  //
  // The first three count routes. The last counts rows, and the
  // difference is not pedantry: a collapsed row stands for the same
  // operation under several prefixes, and those can differ in whether
  // anything calls them. `POST .../daopay-kyc-contract/generate` is
  // live unscoped and dead under both scope prefixes. Counted per
  // route it looks two-thirds stale; badged per row it would tell a
  // reader a route the portal calls today is abandoned. A row is
  // stale only when NOTHING it covers is called.
  result.called = 0;
  result.uncalled = 0;
  result.gap = 0;
  const liveDocs = new Set();
  for (const key of routes) {
    const twins = collapsedKeys(key, false);
    const documented = docs.has(key) || twins.some((t) => docs.has(t.key));
    if (callState(key, calls)) {
      result.called++;
      if (!documented) result.gap++;
      // A collapse only stands in where there is no direct row. Both
      // exist for product addons - the scoped form has its own row and
      // an unscoped route exists that nothing calls - and crediting
      // the twin as well would mark the unscoped row live on the
      // strength of a call to a different route.
      // A route collapses onto exactly ONE row: its own if it has one,
      // otherwise the first documented twin in rule order, which is
      // why the more specific rules are listed first. Crediting every
      // documented twin marks rows live on the strength of a call to a
      // different route - the sales-team addons call would have made
      // both the partner row and an unscoped row nothing calls look
      // live at once.
      if (docs.has(key)) liveDocs.add(key);
      else {
        const stands = twins.find((t) => docs.has(t.key));
        if (stands) liveDocs.add(stands.key);
      }
    } else {
      result.uncalled++;
    }
  }
  // A phantom row documents no route at all, so it cannot be stale -
  // it is already counted, and more sharply, as phantom.
  result.stale_docs = 0;
  for (const key of docs) if (routes.has(key) && !liveDocs.has(key)) result.stale_docs++;
  result.called_pct = routes.size
    ? Math.round((result.called / routes.size) * 1000) / 10 : 0;
  return result;
}

function build(specs, inventory, calls) {
  const out = {
    generated_note: "GENERATED by scripts/gen-coverage.js. Counts and a digest only - " +
      "no paths, hosts or payloads. Do not edit by hand.",
    generated_on: new Date().toISOString().slice(0, 10),
    source: {
      route_digest: inventory.digest,
      routes: inventory.total,
      controllers: inventory.controllers,
      by_version: inventory.byVersion,
    },
    specs: {},
  };
  if (calls) {
    out.consumer = {
      call_digest: calls.digest,
      call_sites: calls.sites,
      resolved: calls.resolved,
      unresolved: calls.unresolved,
      files: calls.files,
      distinct_routes: calls.distinct,
    };
  }
  const routeKeys = inventory.routes.map((r) => routeKey(r.method, r.path));
  const callKeys = calls ? calls.keys : null;
  for (const spec of specs) {
    // Only a live launchpad spec has source to compare against. A draft
    // spec describes design intent and Merchant Portal has no source supplied, so
    // both report their size and abstain rather than showing a coverage
    // figure that would read as verified.
    const gradeable = spec.family === "launchpad" && spec.status === "live";
    const rec = gradeable
      ? reconcile(routeKeys, spec.keys, callKeys, spec.scope_keys)
      : { documented: spec.endpoints };
    // Two rows normalising to one path is invisible to the
    // reconciliation - a spec with no source to compare against is not
    // reconciled at all - so it is counted here for every spec. Merchant Portal
    // carries two: {id} and {numId} forms of the same resource.
    var distinct = spec.distinct_keys == null ? spec.endpoints : spec.distinct_keys;
    out.specs[spec.title] = Object.assign({
      version: spec.version, status: spec.status, family: spec.family,
      endpoints: spec.endpoints, tags: spec.tags, topics: spec.topics,
      duplicates: Math.max(0, spec.endpoints - distinct),
      unverified_badges: spec.badges.unverified || 0,
      gap_badges: spec.badges.gap || 0,
      // The badge that says a documented route has no front-end
      // consumer. Counted so the gate can hold it equal to the
      // derived figure: badge one row too few and a reader takes a
      // superseded route for today's surface.
      consumer_badges: spec.badges["no portal consumer"] || 0,
      comparable: Boolean(gradeable),
    }, rec);
  }
  return out;
}

if (require.main === module) {
  const args = process.argv.slice(2);
  if (!args.includes("--write")) {
    console.log(SQL);
    process.exit(0);
  }
  // --restamp: re-verify the DATABASE half against a fresh query and, if
  // it is unchanged, move generated_on forward. It exists because the
  // staleness gate compares the artefact's date against the newest
  // migration whatever that migration touched, and a migration about
  // function security cannot change an endpoint count. Without this the
  // only ways out were to hand-edit a generated file or to weaken the
  // gate. It refuses if anything the database drives has actually moved,
  // so it can never launder real drift into a fresh date. The source and
  // consumer halves are content digests of a checkout this repo does not
  // contain: an unchanged digest is its own claim, and --restamp does not
  // touch them.
  if (args.includes("--restamp")) {
    const payload = JSON.parse(fs.readFileSync(0, "utf8"));
    const fresh = payload.specs || payload;
    const current = JSON.parse(fs.readFileSync(OUT, "utf8"));
    const drift = [];
    for (const row of fresh) {
      const held = current.specs[row.title];
      if (!held) { drift.push(`${row.title}: in the database, absent from the artefact`); continue; }
      for (const key of ["version", "status", "family", "endpoints", "tags", "topics"]) {
        if (held[key] !== row[key]) {
          drift.push(`${row.title}.${key}: artefact ${held[key]}, database ${row[key]}`);
        }
      }
    }
    for (const title of Object.keys(current.specs)) {
      if (!fresh.some((r) => r.title === title)) drift.push(`${title}: in the artefact, absent from the database`);
    }
    if (drift.length) {
      console.error("Cannot re-stamp: the database half has moved.\n  " +
        drift.join("\n  ") + "\nRe-derive properly with --source instead.");
      process.exit(1);
    }
    current.generated_on = new Date().toISOString().slice(0, 10);
    fs.writeFileSync(OUT, JSON.stringify(current, null, 2) + "\n");
    console.log("re-stamped " + path.relative(ROOT, OUT) + " to " +
      current.generated_on + "; " + fresh.length + " specs re-verified, no drift");
    process.exit(0);
  }

  const source = args[args.indexOf("--source") + 1];
  if (!source || source.startsWith("--")) {
    console.error("Usage: node scripts/gen-coverage.js --write --source <dir> " +
      "[--consumer <portal-src>] < result.json\n" +
      "       node scripts/gen-coverage.js --write --restamp < result.json");
    process.exit(2);
  }
  // The consumer checkout is optional: without it the artefact keeps
  // its previous shape rather than reporting every route as uncalled,
  // which is the failure mode that would matter.
  const consumerArg = args.indexOf("--consumer");
  const consumer = consumerArg === -1 ? null : args[consumerArg + 1];
  const payload = JSON.parse(fs.readFileSync(0, "utf8"));
  const specs = payload.specs || payload;
  const artefact = build(specs, extractDir(source),
    consumer ? extractCalls(consumer) : null);
  fs.writeFileSync(OUT, JSON.stringify(artefact, null, 2) + "\n");
  console.log("wrote " + path.relative(ROOT, OUT));
  for (const [title, s] of Object.entries(artefact.specs)) {
    console.log("  " + title + ": " +
      (s.comparable
        ? `${s.accounted}/${s.routes} accounted (${s.accounted_pct}%), ` +
          `${s.phantom} phantom, ${s.absent} absent`
        : `${s.documented} documented, not comparable against source`));
    if (s.called !== undefined) {
      console.log("    " + `${s.called} called by the portal (${s.called_pct}%), ` +
        `${s.uncalled} called by nothing, ${s.gap} called but undocumented, ` +
        `${s.stale_docs} documented but uncalled`);
    }
  }
}

module.exports = { SQL, COLLAPSES, collapsedKeys, callState, reconcile, build };
