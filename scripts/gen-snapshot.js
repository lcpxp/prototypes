#!/usr/bin/env node
// ------------------------------------------------------------------
// scripts/gen-snapshot.js - Generates supabase/schema-snapshot.json,
// the repo's committed account of what the live database actually
// contains: tables and columns, policy names, functions, views,
// installed extensions and the applied migration ledger.
//
// Why a committed snapshot rather than a live check: the test suite is
// zero-dependency Node with no database access and no credentials, by
// design. So the database describes itself once, into a file, and
// tests/checks/schema-drift.test.js asserts the schema files account
// for everything in it. Same pattern as docs/CODEMAP.md - a generated
// artefact the gates read.
//
// It exists because five applied migrations and two work_items columns
// lived only in the live database, and supabase/schema/ selected one of
// those columns without declaring it, so the schema directory could not
// be run against a fresh project. Nothing caught that.
//
// Usage (needs a session with Supabase MCP access):
//   npm run snapshot                 print the SQL to run
//   <run it, save the single json value to a file>
//   node scripts/gen-snapshot.js --write < result.json
//
// Deliberately never reads the vault schema: secrets do not enter the
// repo, and schema-drift.test.js asserts the snapshot has none.
// ------------------------------------------------------------------
"use strict";
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "supabase", "schema-snapshot.json");

const SQL = `-- Generated by scripts/gen-snapshot.js. Returns one json value.
-- Column NAMES only: the gate checks that every live column is declared
-- somewhere in supabase/schema/, and types would quadruple the file for
-- no assertion. Never reads vault contents.
select jsonb_pretty(jsonb_build_object(
  'generated_note', 'GENERATED by scripts/gen-snapshot.js from the live database. Do not edit by hand.',
  'tables', (
    select jsonb_object_agg(t.table_name, t.cols)
      from (
        select c.table_name,
               jsonb_agg(c.column_name order by c.column_name) as cols
          from information_schema.columns c
          join information_schema.tables tb
            on tb.table_schema = c.table_schema
           and tb.table_name = c.table_name
           and tb.table_type = 'BASE TABLE'
         where c.table_schema = 'public'
         group by c.table_name
      ) t
  ),
  'views', (
    select coalesce(jsonb_agg(table_name order by table_name), '[]'::jsonb)
      from information_schema.views where table_schema = 'public'
  ),
  'policies', (
    select coalesce(jsonb_agg(
             jsonb_build_object('table', tablename, 'name', policyname)
             order by tablename, policyname), '[]'::jsonb)
      from pg_policies where schemaname = 'public'
  ),
  'rls_disabled', (
    select coalesce(jsonb_agg(c.relname order by c.relname), '[]'::jsonb)
      from pg_class c join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'public' and c.relkind = 'r' and not c.relrowsecurity
  ),
  'functions', (
    select coalesce(jsonb_agg(p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')'
                              order by p.proname), '[]'::jsonb)
      from pg_proc p join pg_namespace n on n.oid = p.pronamespace
     where n.nspname = 'public'
  ),
  'extensions', (
    select coalesce(jsonb_agg(jsonb_build_object(
             'name', e.extname,
             'schema', n.nspname,
             'version', e.extversion) order by e.extname), '[]'::jsonb)
      from pg_extension e join pg_namespace n on n.oid = e.extnamespace
  ),
  'migrations', (
    select coalesce(jsonb_agg(jsonb_build_object('version', version, 'name', name)
                              order by version), '[]'::jsonb)
      from supabase_migrations.schema_migrations
  )
)) as snapshot;`;

// Sort object keys recursively so the committed file diffs quietly.
function sorted(value) {
  if (Array.isArray(value)) return value.map(sorted);
  if (value && typeof value === "object") {
    const out = {};
    for (const key of Object.keys(value).sort()) out[key] = sorted(value[key]);
    return out;
  }
  return value;
}

function write(raw) {
  let parsed;
  try {
    parsed = JSON.parse(raw);
  } catch (e) {
    console.error("Input is not JSON. Pipe the single `snapshot` value in:\n" +
      "  node scripts/gen-snapshot.js --write < result.json");
    process.exit(1);
  }
  // Accept either the bare object or the MCP row wrapper [{snapshot: "..."}].
  if (Array.isArray(parsed)) parsed = parsed[0];
  if (parsed && typeof parsed.snapshot === "string") parsed = JSON.parse(parsed.snapshot);
  if (parsed && typeof parsed.snapshot === "object" && parsed.snapshot) parsed = parsed.snapshot;

  // The supabase_vault EXTENSION is legitimate to record; its CONTENTS are
  // not. Match secret-shaped keys, not the word "vault".
  const leak = /decrypted_secret|"secret"|service_role|sb_secret_/i;
  if (leak.test(JSON.stringify(parsed))) {
    console.error("Refusing to write: the snapshot looks like it carries secret " +
      "material. Secrets never enter the repo.");
    process.exit(1);
  }
  fs.writeFileSync(OUT, JSON.stringify(sorted(parsed), null, 2) + "\n");
  const t = Object.keys(parsed.tables || {}).length;
  console.log(`Snapshot: ${t} tables, ${(parsed.policies || []).length} policies, ` +
    `${(parsed.migrations || []).length} migrations. Wrote supabase/schema-snapshot.json.`);
}

if (process.argv.includes("--write")) {
  write(fs.readFileSync(0, "utf8"));
} else {
  console.log(SQL);
}

module.exports = { SQL };
